package vn.edu.uit.mobile.data

import java.io.File
import kotlinx.coroutines.runBlocking
import org.junit.Assert.*
import org.junit.Assume.assumeTrue
import org.junit.Test
import vn.edu.uit.mobile.daa.PublicAnnouncementClient
import vn.edu.uit.mobile.domain.*

class AssistantPublicCaptureTest {
    @Test fun capturePublicContextWithoutUsingACredentialOrGeneratingAnAnswer() = runBlocking {
        assumeTrue(java.lang.Boolean.getBoolean("uit.assistant.live"))
        val output = File(requireNotNull(System.getProperty("uit.assistant.live.output"))).apply { mkdirs() }
        val storage = AssistantMemory()
        val notices = LocalAnnouncementRepository(PublicAnnouncementClient(), storage)
        notices.refresh()
        assertFalse(notices.state.value.sources.getValue(AnnouncementSource.PORTAL).failed)
        assertTrue(notices.state.value.items.isNotEmpty())
        val workspaces = AssistantMemory()
        val repo = LocalAssistantRepository(workspaces, notices, { error("No model access in public context capture") })
        repo.create("UIT announcements", AssistantScope())
        val first = notices.state.value.items.sortedByDescending { it.publishedDate }.first()
        repo.create(first.title.take(80), AssistantScope(setOf(first.source), setOf(first.url)))
        File(output, "public-workspaces.json").writeText(requireNotNull(workspaces.entries["library"]))
        File(output, "public-notices.json").writeText(requireNotNull(storage.entries["inbox"]))
        File(output, "public-context-provenance.txt").writeText("Captured: ${java.time.Instant.now()}\nSources: ${AnnouncementSource.PORTAL.page(0)}, ${AnnouncementSource.PORTAL.page(1)}\nProduction public client/repository; no AI or university credentials.\nWorkspace names are local user labels. No model answers were authored or generated by this capture.\n")
    }
}
