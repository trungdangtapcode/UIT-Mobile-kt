package vn.edu.uit.mobile

import android.app.Application
import androidx.compose.runtime.*
import androidx.compose.ui.test.*
import androidx.compose.ui.test.junit4.createComposeRule
import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import vn.edu.uit.mobile.dashboard.*
import vn.edu.uit.mobile.designsystem.*
import vn.edu.uit.mobile.domain.*

/** Behavior-only synthetic fixtures. No published captures are generated by these tests. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35], qualifiers = "w390dp-h844dp-mdpi", application = Application::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class AssistantDesignTest {
    @get:Rule val compose = createComposeRule()
    private val source = AssistantEvidence("e", "https://portal.uit.edu.vn/bai-viet/fixture", AnnouncementSource.PORTAL, "Fixture scholarship notice", "2026-11-03", 1793700000, "a".repeat(64), listOf("Submit an application before Friday."))
    private val turn = AssistantTurn("turn", "What should I prepare?", 1793700000, AssistantTurnStatus.COMPLETE, listOf(AssistantFact(AssistantFactKind.FACT, "Prepare an application.", listOf(AssistantReference("e", 0, "Submit an application before Friday.")))), listOf(source))
    private val workspace = AssistantWorkspace("workspace", "My notices", AssistantScope(), 1793700000, listOf(turn))
    private val state = AssistantUiState(AssistantLibrary(listOf(workspace)), workspace.id, StudyConnection(configured = true, model = "fixture-model"))

    @Test fun creatingWorkspaceDoesNotSendAQuestionAndRequiresNameAndAllowedSources() {
        var created = false
        var sent = false
        compose.setContent { UitTheme { AssistantContent(AssistantUiState(), onCreate = { _, _ -> created = true }, onAsk = { sent = true }) } }
        compose.onNodeWithText("Create workspace").performClick()
        compose.onNodeWithText("Save", substring = false).assertIsNotEnabled()
        compose.onNodeWithText("Workspace name").performTextInput("Scholarships")
        compose.onNodeWithText("Save", substring = false).performScrollTo().performClick()
        assertTrue(created)
        assertFalse(sent)
    }

    @Test fun explicitSendAndStopControlsDoNotAutomaticallyRetryFailedQuestions() {
        var sent = ""
        var stopped = false
        compose.setContent { UitTheme { AssistantContent(state, onAsk = { sent = it }, onStop = { stopped = true }) } }
        assertEquals("", sent)
        compose.onNodeWithContentDescription("Send message").assertIsNotEnabled()
        compose.onNodeWithTag("assistant-question").performTextInput("What changed?")
        compose.onNodeWithContentDescription("Send message").performClick()
        assertEquals("What changed?", sent)
        assertFalse(stopped)
    }

    @Test fun sourceInspectionShowsTheExactQuoteAndOriginalNavigation() {
        var url = ""
        compose.setContent { UitTheme { AssistantContent(state, onOriginal = { url = it }) } }
        compose.onNodeWithTag("assistant-content").performScrollToNode(hasText("Sources · 1"))
        compose.onNodeWithText("Sources · 1").performClick()
        compose.onNodeWithTag("assistant-content").performScrollToNode(hasTestTag("assistant-reference-turn-0"))
        compose.onNodeWithTag("assistant-reference-turn-0").performClick()
        compose.onAllNodesWithText("Submit an application before Friday.").onFirst().assertExists()
        compose.onNodeWithText("Open original source").performScrollTo().performClick()
        assertEquals(source.url, url)
    }

    @Test fun checklistCreationRequiresReviewAndExplicitSave() {
        var saved = emptyList<AssistantChecklistItem>()
        compose.setContent { UitTheme { AssistantContent(state, onChecklist = { _, _, items -> saved = items }) } }
        compose.onNodeWithTag("assistant-content").performScrollToNode(hasContentDescription("Draft a local checklist"))
        compose.onNodeWithContentDescription("Draft a local checklist").performClick()
        assertTrue(saved.isEmpty())
        compose.onNodeWithText("One task per line").performTextReplacement("Read requirements\nPrepare an application")
        compose.onNodeWithText("Save", substring = false).performScrollTo().performClick()
        assertEquals(listOf("Read requirements", "Prepare an application"), saved.map { it.text })
    }

    @Test fun deletingHistoryRequiresConfirmation() {
        var deleted = false
        compose.setContent { UitTheme { AssistantContent(state.copy(selected = null), onDelete = { deleted = true }) } }
        compose.onNodeWithText("Delete workspace").performClick()
        assertFalse(deleted)
        compose.onAllNodesWithText("Delete workspace").onLast().performClick()
        assertTrue(deleted)
    }

    @Test fun noConnectionKeepsSendDisabledAndThePublicOnlyScopeVisible() {
        compose.setContent { UitTheme { AssistantContent(state.copy(connection = StudyConnection())) } }
        compose.onNodeWithTag("assistant-question").performTextInput("Question")
        compose.onNodeWithContentDescription("Send message").assertIsNotEnabled()
        compose.onNodeWithContentDescription("Context and sources").performClick()
        compose.onNodeWithText("This workspace reads selected public university notices and explicitly attached public Forum posts. Personal records, course files, private topics and messages are excluded.").assertExists()
    }

    @Test fun activeRequestOffersStopAndDisablesSecondSend() {
        var stopped = false
        val running = state.copy(busy = true, progress = AssistantProgress("read_announcement"), library = AssistantLibrary(listOf(workspace.copy(turns = listOf(turn.copy(status = AssistantTurnStatus.RUNNING, facts = emptyList(), evidence = emptyList()))))))
        compose.setContent { UitTheme { AssistantContent(running, onStop = { stopped = true }) } }
        compose.onNodeWithTag("assistant-progress").assertExists()
        compose.onNodeWithContentDescription("Stop").performClick()
        assertTrue(stopped)
        compose.onNodeWithContentDescription("Send message").assertDoesNotExist()
    }

    @Test fun sourcesAreCollapsedAndMessageRolesRemainDistinct() {
        compose.setContent { UitTheme { AssistantContent(state) } }
        compose.onNodeWithTag("assistant-content").performScrollToIndex(0)
        compose.onNodeWithTag("assistant-user-turn").assertExists()
        compose.onNodeWithTag("assistant-answer-turn-0").assertExists()
        compose.onNodeWithText("[1] Portal UIT · 2026-11-03").assertDoesNotExist()
    }

    @Test fun streamedPreviewIsLabelledAsDraftAndHasNoSourceOrChecklistActions() {
        val running = state.copy(busy = true, progress = AssistantProgress("writing", draft = "Receiving an unverified answer."), library = AssistantLibrary(listOf(workspace.copy(turns = listOf(turn.copy(status = AssistantTurnStatus.RUNNING, facts = emptyList(), evidence = emptyList()))))))
        compose.setContent { UitTheme { AssistantContent(running) } }
        compose.onNodeWithTag("assistant-draft").assertTextEquals("Receiving an unverified answer.")
        compose.onNodeWithText("Draft · citations not checked yet").assertExists()
        compose.onNodeWithTag("assistant-sources-turn").assertDoesNotExist()
        compose.onNodeWithContentDescription("Draft a local checklist").assertDoesNotExist()
    }

    @Test fun forumSummaryPresetFillsTheComposerWithoutCallingTheModel() {
        var sent = ""
        val forum = workspace.copy(scope = AssistantScope(emptySet(), forum = AssistantForumScope(7)), turns = emptyList())
        compose.setContent { UitTheme { AssistantContent(state.copy(library = AssistantLibrary(listOf(forum))), onAsk = { sent = it }) } }
        compose.onNodeWithText("Summarize selected posts").performClick()
        assertEquals("", sent)
        compose.onNodeWithTag("assistant-question").assertTextContains("Summarize the selected public Forum posts", substring = true)
        compose.onNodeWithContentDescription("Send message").performClick()
        assertTrue(sent.contains("Attribute claims"))
    }

    @Test fun forumSourceRecheckIsExplicitAndDoesNotGenerateAnotherAnswer() {
        var checked = ""
        var sent = false
        val post = AssistantForumPost(7, 22, 5, "author22", "2026-11-01", "2026-11-02", 2)
        val evidence = source.copy(id = "forum_7_22", url = "https://forum.uit.edu.vn/t/7/5", source = null, forum = post)
        val coverage = AssistantForumCoverage(7, "Public topic", 1, 100, listOf(22), listOf(22), emptyList(), 5, 5, true, true, "", "a".repeat(64), "b".repeat(64), false)
        val reply = turn.copy(evidence = listOf(evidence), facts = listOf(AssistantFact(AssistantFactKind.FACT, "Prepare an application.", listOf(AssistantReference(evidence.id, 0, "Submit an application before Friday.")))), forumCoverage = coverage)
        val forum = workspace.copy(scope = AssistantScope(emptySet(), forum = AssistantForumScope(7, 5, 1)), turns = listOf(reply))
        compose.setContent { UitTheme { AssistantContent(state.copy(library = AssistantLibrary(listOf(forum))), onRecheckForum = { checked = it }, onAsk = { sent = true }) } }
        compose.onNodeWithTag("assistant-forum-coverage").assertExists()
        compose.onNodeWithText("This covers a selected window. Other posts exist outside it.").assertExists()
        compose.onNodeWithTag("assistant-content").performScrollToNode(hasTestTag("assistant-recheck-turn"))
        compose.onNodeWithTag("assistant-recheck-turn").performClick()
        assertEquals("turn", checked)
        assertFalse(sent)
    }

    @Test fun invalidForumLinkCannotCreateAWorkspace() {
        var selected: AssistantScope? = null
        compose.setContent { UitTheme { AssistantContent(AssistantUiState(), onCreate = { _, scope -> selected = scope }) } }
        compose.onNodeWithText("Create workspace").performClick()
        compose.onNodeWithText("Workspace name").performTextInput("Forum research")
        compose.onNodeWithTag("assistant-include-forum").performScrollTo().performClick()
        compose.onNodeWithTag("assistant-forum-url").performScrollTo().performTextInput("https://evil.example/t/7")
        compose.onNodeWithText("Save", substring = false).performScrollTo().assertIsNotEnabled()
        compose.onNodeWithTag("assistant-forum-url").performScrollTo().performTextReplacement("https://forum.uit.edu.vn/t/7/5")
        compose.onNodeWithText("Save", substring = false).performScrollTo().performClick()
        assertEquals(AssistantForumScope(7, 5, 20), selected?.forum)
    }
}
